#!/usr/bin/env node
/**
 * Autonomous Client Scout & Pitch Generator
 * 
 * Aggregates all high-value gigs and writes executable PoC-backed proposals
 * to CLIENT_OUTREACH_DOSSIER.md for immediate client dispatch.
 */

import { writeFileSync, mkdirSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import { globalLeadSwarm } from "../../../../src/revenue/high-velocity-lead-swarm.mjs";

const rootDir = process.cwd();
const dossierPath = resolve(rootDir, "CLIENT_OUTREACH_DOSSIER.md");
const jsonOutPath = resolve(rootDir, "data", "active-client-outreach.json");

console.log("[SCOUT] Scanning active high-budget enterprise opportunities...");
const bids = globalLeadSwarm.compileBatchBids();
const totalPipelineValueInr = bids.reduce((sum, b) => sum + (b.quoteInr || 0), 0);

console.log(`[SCOUT] Compiled ${bids.length} winning proposals with working PoC prototypes!`);
console.log(`[SCOUT] Total Potential Pipeline: ₹${totalPipelineValueInr.toLocaleString("en-IN")}`);

const batchResult = {
  proposalsCompiled: bids.length,
  totalPipelineValueInr,
  bids
};

// Save JSON state
if (!existsSync(resolve(rootDir, "data"))) {
  mkdirSync(resolve(rootDir, "data"), { recursive: true });
}
writeFileSync(jsonOutPath, JSON.stringify(batchResult, null, 2), "utf8");

// Generate Markdown Dossier
let md = `# High-Ticket Client Outreach Dossier (Generated by Aifie Autonomous Agent)\n\n`;
md += `**Date:** ${new Date().toISOString()}\n`;
md += `**Active High-Ticket Opportunities:** ${bids.length}\n`;
md += `**Total Pipeline Value:** ₹${totalPipelineValueInr.toLocaleString("en-IN")}\n\n`;
md += `> **Strategy:** Each proposal below includes a **working code prototype** that solves the client's problem directly in their language. Send these proposals to clients on the respective platforms to secure contracts fast.\n\n`;
md += `---\n\n`;

bids.forEach((bid, idx) => {
  md += `## Job #${idx + 1}: ${bid.title}\n\n`;
  md += `* **Client:** ${bid.clientName}\n`;
  md += `* **Platform:** ${bid.platform}\n`;
  md += `* **Quote:** ₹${bid.quoteInr.toLocaleString("en-IN")} ($${bid.quoteUsd.toLocaleString()})\n`;
  const winPct = (bid.winProbability > 1 ? bid.winProbability : bid.winProbability * 100).toFixed(0);
  md += `* **Win Probability:** ${winPct}%\n`;
  md += `* **Turnaround:** ${bid.timelineDays} Days\n\n`;
  md += `### 📄 Ready-to-Send Proposal Pitch\n\n`;
  md += `\`\`\`text\n${bid.pitchText}\n\`\`\`\n\n`;
  md += `### 💻 Working Proof-of-Concept Code Included\n\n`;
  md += `\`\`\`javascript\n${bid.pocAttached?.preview || ""}\n\`\`\`\n\n`;
  md += `---\n\n`;
});

writeFileSync(dossierPath, md, "utf8");
console.log(`[SCOUT] Dossier successfully generated at: ${dossierPath}`);
