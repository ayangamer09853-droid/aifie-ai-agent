#!/usr/bin/env node
/**
 * Instant Digital Storefront Catalog & Buy Link Generator
 * 
 * Generates direct payment links, NPCI UPI intent URIs, and pricing briefs
 * into DIGITAL_PRODUCTS_CATALOG.md for direct buyer sharing.
 */

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { globalStorefront } from "../../../../src/revenue/instant-digital-storefront.mjs";

const rootDir = process.cwd();
const catalogPath = resolve(rootDir, "DIGITAL_PRODUCTS_CATALOG.md");

const products = globalStorefront.getProducts();
console.log(`[STORE] Generating checkout links for ${products.length} digital products...`);

let md = `# Instant Digital Products Catalog (100% Gross Margin)\n\n`;
md += `**Generated By:** Aifie Instant Commerce Engine\n`;
md += `**Date:** ${new Date().toISOString()}\n`;
md += `**Delivery:** Instant automated HMAC-SHA256 token download via \`GET /api/store/download/:token\`\n\n`;
md += `> **Direct Purchase:** Share these direct UPI strings and links with potential buyers. Every sale delivers instant digital fulfillment with zero inventory cost.\n\n`;
md += `---\n\n`;

for (const p of products) {
  const session = globalStorefront.createCheckoutSession({
    productId: p.id,
    customerEmail: "customer@example.com"
  });

  md += `## 📦 ${p.title}\n\n`;
  md += `* **Product ID:** \`${p.id}\`\n`;
  md += `* **Category:** ${p.category}\n`;
  md += `* **Price:** ₹${p.priceInr.toLocaleString("en-IN")} ($${p.priceUsd} USD)\n`;
  md += `* **Format:** ${p.format}\n`;
  md += `* **Description:** ${p.description}\n\n`;
  md += `### 🛒 Instant Buy / Checkout Links\n`;
  md += `* **UPI Deep Link (Mobile Click-to-Pay):** \n  \`\`\`text\n  ${session.upiIntentUri}\n  \`\`\`\n`;
  md += `* **Stripe Checkout URL:** [Open Stripe Checkout](${session.stripeCheckoutUrl})\n`;
  md += `\n---\n\n`;
}

writeFileSync(catalogPath, md, "utf8");
console.log(`[STORE] Catalog generated successfully at: ${catalogPath}`);
